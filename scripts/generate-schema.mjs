import { readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..');
const names = (await readdir(resolve(root, 'migrations'))).filter(name => /^\d+_.+\.sql$/.test(name)).sort();
const migrations = [];
for (const name of names) {
  const sql = await readFile(resolve(root, 'migrations', name), 'utf8');
  // The checked-in migrations contain no semicolons in quoted literals.
  const statements = sql.replace(/--[^\n]*/g, '').split(';').map(s => s.trim()).filter(s => s && !/^PRAGMA\s+foreign_keys\b/i.test(s))
    .map(s => s.replace(/^CREATE TABLE (?!IF NOT EXISTS)/i, 'CREATE TABLE IF NOT EXISTS ').replace(/^CREATE INDEX (?!IF NOT EXISTS)/i, 'CREATE INDEX IF NOT EXISTS '));
  migrations.push({ name, statements });
}
const text = '// Generated by npm run schema:generate. Do not edit directly.\nexport const migrations = ' + JSON.stringify(migrations, null, 2) + ' as const;\n';
const target = resolve(root, 'src/storage/schema.ts');
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8').catch(() => '') !== text) throw new Error('Embedded schema is stale; run npm run schema:generate.');
} else await writeFile(target, text);
